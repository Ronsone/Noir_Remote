"""Render the TV source logos for the firmware (run after changing custom_components/noir_remote/logos.json).

  python tools/make_logos.py

Writes firmware/logos/<key>.png (34 x 34, light grey on transparent), a copy for the NOIR Builder,
firmware/logos.yaml (ESPHome package) and simulator/assets/logos.h.
Needs rsvg-convert (librsvg) and Pillow.
"""
import json
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "logos" / "svg"
OUT = ROOT / "firmware" / "logos"
WEB = ROOT / "custom_components" / "noir_remote" / "frontend" / "logos"   # same PNGs for the Builder preview
COLOR = "#E4E7EC"
SIZE = 34


def svg_text(key: str, generic: bool) -> str:
    s = (SRC / f"{key}.svg").read_text()
    if generic:   # Lucide: outline, thin stroke
        s = s.replace("currentColor", COLOR)
        s = re.sub(r'stroke-width="[^"]*"', 'stroke-width="1.5"', s)
    else:         # Simple Icons: one filled path
        s = s.replace("<svg ", f'<svg fill="{COLOR}" ', 1)
    return s


def sim_header(keys) -> None:
    """Same logos for the simulator (ARGB8888, LVGL byte order B G R A)."""
    from PIL import Image
    out = ["// Generated by tools/make_logos.py - do not edit.", "#pragma once", '#include "lvgl.h"']
    reg = []
    for key, _ in keys:
        im = Image.open(OUT / f"{key}.png").convert("RGBA")
        px = ",".join(f"{b},{g},{r},{a}" for r, g, b, a in im.getdata())
        out.append(f"static const uint8_t logo_{key}_px[] = {{{px}}};")
        out.append(f"static const lv_image_dsc_t logo_{key} = {{.header = {{.magic = LV_IMAGE_HEADER_MAGIC, "
                   f".cf = LV_COLOR_FORMAT_ARGB8888, .w = {im.width}, .h = {im.height}, .stride = {im.width * 4}}}, "
                   f".data_size = sizeof(logo_{key}_px), .data = logo_{key}_px}};")
        reg.append(f'  noir::logos()["{key}"] = &logo_{key};')
    out += ["inline void sim_logos() {", *reg, "}", ""]
    (ROOT / "simulator" / "assets" / "logos.h").write_text("\n".join(out))


def main() -> None:
    logos = json.loads((ROOT / "custom_components" / "noir_remote" / "logos.json").read_text())
    OUT.mkdir(exist_ok=True)
    WEB.mkdir(exist_ok=True)
    keys = [(k, False) for k in logos["brands"]] + [(k, True) for k in logos["generic"]]
    for key, generic in keys:
        subprocess.run(["rsvg-convert", "-w", str(SIZE), "-h", str(SIZE), "-o", str(OUT / f"{key}.png")],
                       input=svg_text(key, generic).encode(), check=True)
        (WEB / f"{key}.png").write_bytes((OUT / f"{key}.png").read_bytes())
    lines = ["# Generated by tools/make_logos.py - do not edit. Logos for the TV source tiles.", "image:"]
    lines += [f"  - {{platform: file, id: logo_{k}, file: logos/{k}.png, type: RGB565, transparency: alpha_channel}}"
              for k, _ in keys]
    reg = " ".join(f'noirapp::logo("{k}", id(logo_{k}));' for k, _ in keys)
    lines += ["esphome:", "  on_boot:", "    - priority: -90   # before the screens are built (-100)",
              "      then:", f"        - lambda: '{reg}'", ""]
    (ROOT / "firmware" / "logos.yaml").write_text("\n".join(lines))
    sim_header(keys)
    print(f"{len(keys)} logos")


if __name__ == "__main__":
    main()
